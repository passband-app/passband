#!/usr/bin/env python3
"""Session replay's icon vocabulary.

Replay draws an icon in a frame only when the icon's shape matches one of the
app's OWN SF Symbols, and then draws our copy of that symbol, never the
pixels it saw. This script writes that list from the places Sources/ names a
symbol for an icon:

  * any string literal on a line that says `systemName:`, `systemSymbolName:`
    or `systemImage:` (which catches `copied ? "checkmark" : "doc.on.doc"`)
  * any string literal inside a property or function whose name says symbol,
    icon, glyph or systemImage (the enums: `var symbol: String { ... }`)

and then drops DENY: symbols shaped like a letter, digit or punctuation mark,
and bare geometric shapes. Those are what a sender's avatar initial, a logo
or a ringed avatar could match, and drawing one would say something about the
mail. The app keeps only names macOS knows as symbols.

  ./replay-icons.py          rewrite Sources/Passband/Lib/ReplayIconNames.swift
  ./replay-icons.py --check  fail if the file is not what this would write
                             (run by test.sh)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "Sources/Passband/Lib/ReplayIconNames.swift"
LITERAL = re.compile(r'"([a-z][a-z0-9]*(?:\.[a-z0-9]+)*)"')
DIRECT_LINE = re.compile(r"\b(?:systemName|systemSymbolName|systemImage)\s*:")
NAMED = re.compile(
    r"\b(?:var|let|func)\s+\w*(?:symbol|Symbol|icon|Icon|glyph|Glyph|systemImage)\w*\b")

# Shapes a piece of mail can make. Letters and digits (and anything built on
# one), text-format glyphs, punctuation marks, and plain geometric shapes
# that a round avatar or a ring matches about as well as anything.
DENY_EXACT = {
    "a", "k", "at", "bold", "italic", "underline", "strikethrough", "info",
    "exclamationmark", "questionmark", "circle", "circle.fill", "ring",
    "square", "square.fill", "capsule", "capsule.fill", "oval", "oval.fill",
    "rectangle", "rectangle.fill", "seal", "seal.fill", "shield", "shield.fill",
    "left", "right", "space", "return", "shift", "alt", "option", "clear",
    "note", "scroll", "mail",
}
DENY_PREFIX = ("textformat", "character", "number", "a.", "k.", "at.", "exclamationmark.",
               "questionmark.")
DENY_PATTERN = re.compile(r"(^|\.)[a-z0-9](\.|$)")  # a bare letter or digit component


def denied(name: str) -> bool:
    return (name in DENY_EXACT or name.startswith(DENY_PREFIX)
            or bool(DENY_PATTERN.search(name)))


def block_after(text: str, start: int) -> str:
    """The declaration line, plus its brace block if one opens on it."""
    line_end = text.find("\n", start)
    line = text[start:line_end if line_end >= 0 else len(text)]
    brace = line.find("{")
    if brace < 0:
        return line
    depth, i = 0, start + brace
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start:i + 1]
        i += 1
    return text[start:]


def names() -> list[str]:
    found = set()
    for f in sorted((ROOT / "Sources").rglob("*.swift")):
        if f == OUT:
            continue
        text = f.read_text(errors="ignore")
        for line in text.splitlines():
            if DIRECT_LINE.search(line):
                found.update(LITERAL.findall(line))
        for m in NAMED.finditer(text):
            found.update(LITERAL.findall(block_after(text, m.start())))
    return sorted(n for n in found if not denied(n))


def render(ns: list[str]) -> str:
    lines = ",\n".join(f'        "{n}"' for n in ns)
    return f"""// GENERATED by passband/replay-icons.py; do not edit. Rerun it after adding
// an SF Symbol (test.sh fails while this is stale).
//
// The SF Symbols Sources/ names for icons, minus the letter-, digit- and
// shape-like ones a piece of mail could match. Session replay keeps those
// macOS knows as symbols and matches icon shapes against them (see
// ReplayIcons.swift).

enum ReplayIconNames {{
    static let candidates: [String] = [
{lines},
    ]
}}
"""


text = render(names())
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("replay-icons: ReplayIconNames.swift is stale; run passband/replay-icons.py")
    print("replay-icons: ok")
else:
    OUT.write_text(text)
    print(f"replay-icons: wrote {len(names())} candidates")
