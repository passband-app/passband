// Renders the SF Symbols the app mocks use into sf-symbols.ts: one white
// 128px PNG per symbol, as a data URI the page uses as a mask, so each icon
// takes its colour from CSS like the app's do. Every symbol is drawn at the
// same point size and weight, centred, so they sit together as they do in
// the app. Run on a Mac from passband-site/:
//
//   swift tools/sf-symbols.swift > sf-symbols.ts
import AppKit

// Site glyph name -> the SF Symbol the app draws there.
let symbols: [(String, String)] = [
    ("sitrep", "gauge.with.dots.needle.33percent"),
    ("calendar", "calendar"),
    ("mail", "envelope"),
    ("key", "key"),
    ("pulse", "waveform.path.ecg"),
    ("gear", "gearshape"),
    ("update", "arrow.down.circle"),
    ("eye", "eye"),
    ("wind", "wind"),
    ("reading", "envelope.open"),
    ("box", "shippingbox"),
    ("bank", "building.columns"),
    ("receipt", "receipt"),
    ("compose", "square.and.pencil"),
    ("search", "magnifyingglass"),
    ("clip", "paperclip"),
    ("copy", "doc.on.doc"),
    ("done", "checkmark.circle"),
    ("ticket", "ticket"),
    ("back", "chevron.left"),
    ("forward", "chevron.right"),
    ("plus", "plus"),
]

let side = 96
let config = NSImage.SymbolConfiguration(pointSize: 74, weight: .regular)
    .applying(NSImage.SymbolConfiguration(paletteColors: [.white]))

print("// Generated by tools/sf-symbols.swift. Do not edit by hand.")
print("export const SF_SYMBOLS: Record<string, string> = {")
for (name, symbol) in symbols {
    guard let base = NSImage(systemSymbolName: symbol, accessibilityDescription: nil),
          let img = base.withSymbolConfiguration(config) else {
        FileHandle.standardError.write("missing symbol \(symbol)\n".data(using: .utf8)!)
        exit(1)
    }
    let rep = NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: side, pixelsHigh: side, bitsPerSample: 8,
        samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
        bytesPerRow: 0, bitsPerPixel: 0)!
    rep.size = NSSize(width: side, height: side)
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    let s = img.size
    img.draw(in: NSRect(x: (CGFloat(side) - s.width) / 2, y: (CGFloat(side) - s.height) / 2,
                        width: s.width, height: s.height))
    NSGraphicsContext.restoreGraphicsState()
    let png = rep.representation(using: .png, properties: [:])!
    print("  \(name): \"data:image/png;base64,\(png.base64EncodedString())\",")
}
print("};")
