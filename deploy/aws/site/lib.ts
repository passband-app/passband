// Pure pieces of the landing-site build for AWS (S3 + CloudFront), shared by
// build.ts and the test. Everything here is DERIVED from passband-site/server.ts
// and passband-site/appcast.xml rather than restated, so server.ts (the local dev
// server) and the CloudFront Function cannot drift apart silently: the route map and the
// releases repo are parsed out of server.ts's source, the version regex is the
// one server.ts uses, and content types come from Bun's own MIME table (the
// same one Bun.file() hands server.ts at runtime).

/** The version regex in server.ts's latestVersion(), verbatim. */
const VERSION_RE = /<sparkle:shortVersionString>(\d+\.\d+\.\d+)</;

/** The woff2 header server.ts sends; the only Cache-Control it sets. */
export const WOFF2_CACHE_CONTROL = "public, max-age=604800";

/**
 * appcast.xml: server.ts sends no Cache-Control, so served directly nothing
 * caches it. Behind CloudFront an object with no Cache-Control gets the cache
 * policy's default TTL (a day on the managed policies), which would hide a
 * release from Sparkle for that long. DESIGN.md asks for it short-cached.
 */
export const APPCAST_CACHE_CONTROL = "public, max-age=300";

/** Same answer as server.ts's latestVersion() for the same file contents. */
export function latestVersion(appcastXml: string | null): string | null {
  return (appcastXml ?? "").match(VERSION_RE)?.[1] ?? null;
}

/**
 * The `pages` map from server.ts: request path -> file path relative to
 * passband-site/. Parsed from source (server.ts calls Bun.serve at top level,
 * so it cannot be imported). Fails loudly if the shape changes, rather than
 * shipping a function with half a route table.
 */
export function parsePages(serverSrc: string): Record<string, string> {
  const block = serverSrc.match(
    /const pages: Record<string, string> = \{([\s\S]*?)\n\};/,
  );
  if (!block) throw new Error("server.ts: could not find the `pages` map");
  const pages: Record<string, string> = {};
  // Drop line comments first so a quoted path inside a comment is not a route.
  const body = block[1].replace(/^\s*\/\/.*$/gm, "");
  for (const m of body.matchAll(/^\s*"([^"]+)":\s*"([^"]+)",?\s*$/gm)) {
    pages[m[1]] = m[2];
  }
  // Every non-comment, non-blank line must have been an entry.
  const entryLines = body.split("\n").filter((l) => l.trim() !== "");
  if (entryLines.length !== Object.keys(pages).length) {
    throw new Error(
      `server.ts: pages map has ${entryLines.length} entry lines but ${Object.keys(pages).length} parsed; update parsePages`,
    );
  }
  if (Object.keys(pages).length < 5) {
    throw new Error("server.ts: pages map parsed suspiciously small");
  }
  return pages;
}

/** RELEASES_REPO from server.ts. */
export function parseReleasesRepo(serverSrc: string): string {
  const m = serverSrc.match(/const RELEASES_REPO = "([^"]+)";/);
  if (!m) throw new Error("server.ts: could not find RELEASES_REPO");
  return m[1];
}

export type ObjectSpec = {
  /** S3 key, no leading slash; also the path the function rewrites to. */
  key: string;
  /** Source path relative to passband-site/. */
  source: string;
  contentType: string;
  cacheControl: string | null;
};

/** The fallback every unmatched path is served. */
export const INDEX = "index.html";

/**
 * Every object to upload: each `pages` file plus index.html, keyed by the
 * file's own path, with the headers server.ts would have served it with.
 */
export function objectSpecs(pages: Record<string, string>): ObjectSpec[] {
  const out = new Map<string, ObjectSpec>();
  const add = (requestPath: string | null, source: string) => {
    if (source.startsWith("/") || source.includes("..")) {
      throw new Error(`refusing odd source path ${source}`);
    }
    out.set(source, {
      key: source,
      source,
      contentType: Bun.file(source).type,
      // server.ts keys the header on the REQUEST path ending in .woff2.
      cacheControl: requestPath?.endsWith(".woff2")
        ? WOFF2_CACHE_CONTROL
        : source === "appcast.xml"
          ? APPCAST_CACHE_CONTROL
          : null,
    });
  };
  for (const [p, f] of Object.entries(pages)) add(p, f);
  add(null, INDEX);
  return [...out.values()];
}

/**
 * The CloudFront Function (runtime cloudfront-js-2.0, viewer-request). It
 * cannot read files, so the version and the route table are baked in here.
 * Written in conservative ES5-ish JS: the runtime is not Node and lacks some
 * newer syntax.
 */
export function renderFunction(opts: {
  pages: Record<string, string>;
  latest: string | null;
  releasesRepo: string;
}): string {
  const routes: Record<string, string> = {};
  for (const [p, f] of Object.entries(opts.pages)) routes[p] = "/" + f;
  return `// GENERATED by deploy/aws/site/build.ts from passband-site/server.ts and
// passband-site/appcast.xml. Do not edit: change server.ts and rebuild.
// Runtime: cloudfront-js-2.0, viewer-request event. Mirrors server.ts's
// routing exactly; deploy/aws/site/function.test.ts holds it to that.
var LATEST = ${JSON.stringify(opts.latest)};
var RELEASES_REPO = ${JSON.stringify(opts.releasesRepo)};
var ROUTES = ${JSON.stringify(routes, null, 2)};
var DL = /^\\/download\\/(Passband-(\\d+\\.\\d+\\.\\d+)\\.zip)$/;

function redirect(location) {
  return {
    statusCode: 302,
    statusDescription: "Found",
    headers: { location: { value: location } },
  };
}

function handler(event) {
  var request = event.request;
  var path = request.uri;
  if (Object.prototype.hasOwnProperty.call(ROUTES, path)) {
    request.uri = ROUTES[path];
    return request;
  }
  if (path === "/download" || path === "/download/latest") {
    return redirect(
      LATEST
        ? "/download/Passband-" + LATEST + ".zip"
        : "https://github.com/" + RELEASES_REPO + "/releases"
    );
  }
  var dl = path.match(DL);
  if (dl) {
    return redirect(
      "https://github.com/" + RELEASES_REPO + "/releases/download/passband-mac-" +
        dl[2] + "/" + dl[1]
    );
  }
  request.uri = "/${INDEX}";
  return request;
}
`;
}
