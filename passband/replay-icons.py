#!/usr/bin/env python3
"""Session replay's icon vocabulary.

Replay draws an icon in a frame only when the icon's shape matches one of the
app's OWN SF Symbols, and then draws our copy of that symbol, never the
pixels it saw. This script writes that list: every string literal in Sources/
shaped like a symbol name. The app keeps only the ones macOS actually knows as
symbols (`NSImage(systemSymbolName:)`), so ordinary words in the list cost
nothing.

  ./replay-icons.py          rewrite Sources/Passband/Lib/ReplayIconNames.swift
  ./replay-icons.py --check  fail if a `systemName: "..."` literal is missing
                             (run by test.sh)

The check is deliberately narrower than the list: every other literal is a
best-effort extra (enum-driven symbol names live there), so an unrelated new
string never fails CI. Rerun the script whenever icons change.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "Sources/Passband/Lib/ReplayIconNames.swift"
SYMBOLISH = re.compile(r'"([a-z][a-z0-9]*(?:\.[a-z0-9]+)*)"')
DIRECT = re.compile(r'(?:systemName|systemSymbolName):\s*"([a-z0-9.]+)"')


def names() -> list[str]:
    found = set()
    for f in (ROOT / "Sources").rglob("*.swift"):
        if f == OUT:
            continue
        found.update(SYMBOLISH.findall(f.read_text(errors="ignore")))
    return sorted(found)


def render(ns: list[str]) -> str:
    lines = ",\n".join(f'        "{n}"' for n in ns)
    return f"""// GENERATED by passband/replay-icons.py; do not edit. Rerun it after adding
// an SF Symbol (test.sh fails while this is stale).
//
// Every string literal in Sources/ shaped like a symbol name. Session replay
// keeps the ones macOS knows as symbols and matches icon shapes against them
// (see ReplayIcons.swift).

enum ReplayIconNames {{
    static let candidates: [String] = [
{lines},
    ]
}}
"""


def direct() -> set[str]:
    found = set()
    for f in (ROOT / "Sources").rglob("*.swift"):
        found.update(DIRECT.findall(f.read_text(errors="ignore")))
    return found


if "--check" in sys.argv:
    listed = set(re.findall(r'"([^"]+)"', OUT.read_text())) if OUT.exists() else set()
    missing = sorted(direct() - listed)
    if missing:
        sys.exit(f"replay-icons: missing {missing}; run passband/replay-icons.py")
    print("replay-icons: ok")
    sys.exit(0)
OUT.write_text(render(names()))
print(f"replay-icons: wrote {len(names())} candidates")
